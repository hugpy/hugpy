def quant_fit_walk(quants, verdict_by_file, *, ctx_pct=None, trained_by_file=None,
                   kv_cache_type="f16", bnb_on=False):
    """Pure fit-walk shared by the knob write (service) and the testshell's
    re-derivation (react/testshell/api.py). ``verdict_by_file`` maps a GGUF
    basename to its model_worker_quants ``memory`` table; a quant FITS when any
    mode in that table says fits=true AND (no ctx_pct, or that mode's
    ctx_max[kv type] holds the ctx target). Returns (chosen_file_or_None,
    {file: reason_or_None}) — the first fitting quant in list order."""
    kt = "f16" if str(kv_cache_type or "f16") == "bf16" else str(kv_cache_type or "f16")
    reasons = {}
    chosen = None
    for f in list(quants or []):
        mem = (verdict_by_file or {}).get(f)
        if mem is None:
            reasons[f] = "no verdict for this quant on this worker yet"
            continue
        table = (mem.get("bnb_4bit") or {}) if bnb_on else mem
        want = None
        trained = (trained_by_file or {}).get(f)
        if ctx_pct is not None and trained:
            want = max(1024, (int(trained) * int(ctx_pct) // 100) // 1024 * 1024)
        ok_modes = []
        for mode, mm in (table or {}).items():
            if not isinstance(mm, dict) or mm.get("fits") is not True:
                continue
            cap = (mm.get("ctx_max") or {}).get(kt)
            if want is not None and cap is not None and (int(cap) <= 0 or want > int(cap)):
                continue
            ok_modes.append(mode)
        if ok_modes:
            reasons[f] = None
            if chosen is None:
                chosen = f
        else:
            anyfit = any(isinstance(mm, dict) and mm.get("fits") is True for mm in (table or {}).values())
            reasons[f] = (f"fits, but no mode holds the context target {want} at KV {kt}" if (anyfit and want is not None)
                          else "does not fit this worker in any mode")
    return chosen, reasons

# bytes per KV element for each llama.cpp cache type (block-32 formats carry a
# 2-byte scale per 32 elements). The console's pricing uses the same table.
KV_CACHE_TYPES = {"f16": 2.0, "bf16": 2.0, "q8_0": 34 / 32, "q4_0": 18 / 32}
KV_CACHE_TYPES_NEED_FLASH = ("q8_0", "q4_0")
# AUTO mode order when the auto mode's ctx ceiling cannot hold the context
