    SYNC_WORKER_REGISTRY_FUNCTION = """
    CREATE OR REPLACE FUNCTION hugpy_sync_worker_model_rows() RETURNS trigger
    LANGUAGE plpgsql AS $$
    DECLARE
      model_key TEXT;
      allocation_row JSONB;
      activity_row JSONB;
      assigned_row BOOLEAN;
      worker_is_fresh BOOLEAN;
    BEGIN
      IF to_regclass('public.model_workers') IS NULL THEN
        RETURN NEW;
      END IF;
      -- FRESH worker = no pair rows yet: central's designation list seeds the
      -- DB once (operator 2026-10-02: "default for a fresh worker"). A worker
      -- the DB already knows gets NO designations from the payload — a model
      -- central still lists after a DB unassign must not come back as assigned.
      SELECT NOT EXISTS (SELECT 1 FROM model_workers WHERE worker_id = NEW.worker_id)
        INTO worker_is_fresh;
      -- DESIGNATION IS DB-OWNED (operator ruling 2026-10-02: "these should all
      -- be database relays"): the heartbeat refreshes live mechanics only
      -- (allocation/activity). ``assigned`` on an EXISTING row is the operator's
      -- decision written through the console's /assigned route and is never
      -- overwritten from central's payload; a NEW row takes its initial value
      -- from the payload (first import of a designation central already held).
      UPDATE model_workers SET allocation = NULL, activity = '{}'::jsonb,
        updated_at = now() WHERE worker_id = NEW.worker_id;

      -- A (model, worker) row exists only for a pair that is REAL on this worker:
      -- assigned (operator intent) or loading / loaded / allocated right now (live
      -- mechanics). The knob maps (moe_by_model, bnb_by_model, spill_by_model,
      -- model_last_picked) never create a row on their own: a stray pin on an
      -- unassigned model is residue, not a pairing (operator ruling 2026-10-01).
      FOR model_key IN
        SELECT value #>> '{}' FROM jsonb_array_elements(
          CASE WHEN jsonb_typeof(NEW.payload->'models')='array'
               THEN NEW.payload->'models' ELSE '[]'::jsonb END)
          WHERE jsonb_typeof(value)='string'
        UNION
        SELECT value #>> '{}' FROM jsonb_array_elements(
          CASE WHEN jsonb_typeof(NEW.payload->'loaded_models')='array'
               THEN NEW.payload->'loaded_models' ELSE '[]'::jsonb END)
          WHERE jsonb_typeof(value)='string'
        UNION
        SELECT value #>> '{}' FROM jsonb_array_elements(
          CASE WHEN jsonb_typeof(NEW.payload->'loading')='array'
               THEN NEW.payload->'loading' ELSE '[]'::jsonb END)
          WHERE jsonb_typeof(value)='string'
        UNION
        SELECT value->>'model_key' FROM jsonb_array_elements(
          CASE WHEN jsonb_typeof(NEW.payload->'allocations')='array'
               THEN NEW.payload->'allocations' ELSE '[]'::jsonb END)
          WHERE value ? 'model_key'
      LOOP
        IF model_key IS NULL OR btrim(model_key) = '' THEN CONTINUE; END IF;
        INSERT INTO models (name) VALUES (model_key)
          ON CONFLICT (name) DO NOTHING;
        allocation_row := NULL;
        SELECT value INTO allocation_row
          FROM jsonb_array_elements(
            CASE WHEN jsonb_typeof(NEW.payload->'allocations')='array'
                 THEN NEW.payload->'allocations' ELSE '[]'::jsonb END)
          WHERE value->>'model_key'=model_key LIMIT 1;
        IF allocation_row IS NULL AND
           jsonb_typeof(NEW.payload->'spill_by_model')='object' THEN
          allocation_row := NEW.payload->'spill_by_model'->model_key;
        END IF;
        -- user_settings (knobs) are DB-owned operator intent (ruling 2026-10-02:
        -- nothing live depends on central); the registry's moe_by_model /
        -- bnb_by_model maps are NOT merged in. Central reads the DB value instead.
        activity_row := jsonb_build_object(
          'loaded', COALESCE(NEW.payload->'loaded_models' ? model_key, FALSE),
          'loading', COALESCE(NEW.payload->'loading' ? model_key, FALSE));
        IF jsonb_typeof(NEW.payload->'model_last_picked')='object'
           AND NEW.payload->'model_last_picked' ? model_key THEN
          activity_row := activity_row || jsonb_build_object(
            'last_picked', NEW.payload->'model_last_picked'->model_key);
        END IF;
        assigned_row := worker_is_fresh AND COALESCE(jsonb_typeof(NEW.payload->'models')='array'
                                 AND NEW.payload->'models' ? model_key, FALSE);
        INSERT INTO model_workers
          (model_id, worker_id, allocation, user_settings, activity, assigned,
           updated_at)
        SELECT id, NEW.worker_id, allocation_row, '{}'::jsonb,
               activity_row, assigned_row, now() FROM models WHERE name=model_key
        ON CONFLICT (model_id, worker_id) DO UPDATE SET
          allocation = EXCLUDED.allocation,
          activity = EXCLUDED.activity, assigned = model_workers.assigned,
          updated_at = now();
      END LOOP;

      -- Residue: a pair that is neither assigned nor live carries nothing real.
      -- A pair central STILL LISTS keeps its (assigned=false) row until the
      -- designation relay has converged central — otherwise the next heartbeat
      -- would re-create it and the unassign would flap.
      DELETE FROM model_workers
       WHERE worker_id = NEW.worker_id AND NOT assigned AND allocation IS NULL
         AND COALESCE((activity->>'loaded')::boolean, false) = false
         AND COALESCE((activity->>'loading')::boolean, false) = false
         AND NOT (jsonb_typeof(NEW.payload->'models')='array'
                  AND NEW.payload->'models' ? (SELECT name FROM models WHERE id = model_workers.model_id));
      RETURN NEW;
    END;
    $$;
    """

